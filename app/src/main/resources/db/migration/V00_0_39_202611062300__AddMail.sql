CREATE TABLE mail_message
(
	id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	type          ENUM ('inbox', 'draft', 'outbox', 'sent', 'trash') NOT NULL,
	sent          TIMESTAMP(9),
	published     TIMESTAMP(9) NOT NULL,
	location_from BINARY(16),
	identity_from BINARY(16),
	subject       VARCHAR(4096),
	content       VARCHAR(1048576),
	read          BOOLEAN NOT NULL DEFAULT FALSE,
	starred       BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX idx_mail_message_type_published ON mail_message (type, published);

CREATE TABLE mail_message_location_to
(
	mail_message_id BIGINT NOT NULL,
	identifier      BINARY(16) NOT NULL
);
CREATE INDEX idx_mail_message_location_to ON mail_message_location_to (mail_message_id);

CREATE TABLE mail_message_location_cc
(
	mail_message_id BIGINT NOT NULL,
	identifier      BINARY(16) NOT NULL
);
CREATE INDEX idx_mail_message_location_cc ON mail_message_location_cc (mail_message_id);

CREATE TABLE mail_message_location_bcc
(
	mail_message_id BIGINT NOT NULL,
	identifier      BINARY(16) NOT NULL
);
CREATE INDEX idx_mail_message_location_bcc ON mail_message_location_bcc (mail_message_id);

CREATE TABLE mail_message_identity_to
(
	mail_message_id BIGINT NOT NULL,
	identifier      BINARY(16) NOT NULL
);
CREATE INDEX idx_mail_message_identity_to ON mail_message_identity_to (mail_message_id);

CREATE TABLE mail_message_identity_cc
(
	mail_message_id BIGINT NOT NULL,
	identifier      BINARY(16) NOT NULL
);
CREATE INDEX idx_mail_message_identity_cc ON mail_message_identity_cc (mail_message_id);

CREATE TABLE mail_message_identity_bcc
(
	mail_message_id BIGINT NOT NULL,
	identifier      BINARY(16) NOT NULL
);
CREATE INDEX idx_mail_message_identity_bcc ON mail_message_identity_bcc (mail_message_id);

CREATE TABLE mail_message_files
(
	mail_message_id BIGINT NOT NULL,
	size            BIGINT,
	hash            BINARY(20),
	name            VARCHAR(512),
	path            VARCHAR(4096),
	age             INT
);
CREATE INDEX idx_mail_message_files ON mail_message_files (mail_message_id);

CREATE TABLE mail_destination
(
	id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	mail_message_id BIGINT NOT NULL,
	type            ENUM ('location', 'distant') NOT NULL,
	last_try        TIMESTAMP(9) NOT NULL DEFAULT TIMESTAMP '1970-01-01 00:00:00',
	destination     BINARY(16) NOT NULL,
	CONSTRAINT uq_mail_destination UNIQUE (mail_message_id, type, destination)
);
CREATE INDEX idx_mail_destination_message ON mail_destination (mail_message_id);
CREATE INDEX idx_mail_destination_last_try ON mail_destination (last_try);